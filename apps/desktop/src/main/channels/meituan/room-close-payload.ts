/**
 * 美团**关房**的 `changeRaw` 模型 —— **RMS 侧对接美团关房时读这一份**。
 *
 * 数据来源：踩点 `docs/踩点/美团/关房.md`（2026-08-13 真机联调时发现并补的）。
 *
 * ============================================================================
 * ⚠️ 一句话摘要：关房与开房**不是同一个端点**，形状也不同
 * ============================================================================
 *
 * 这是联调时踩到的坑：踩点 `单房态房量01.md` 里开房关房看着都走
 * `inventory/status/switch`，于是最初只认了那一个端点。真机跑下来发现**关房一次都拦不到**
 * —— 用户连点四次「关房」，日志里全是 `status: 1`（那是之前开房留下的）。
 *
 * ```
 * 开房  /goods/inventory/status/switch            {status:1, startDate, endDate, syncChecked}
 * 关房  /goods/inventory/roomstatus/submitaudit   {status:0, date, goodsIds[], reason, roomName}
 * ```
 *
 * ⚠️ **`submitaudit` 这个词是有含义的**：关房要**走审核**。所以「拦到了」只代表用户提交了
 * 关房申请，**不代表房态已经关上** —— 与携程新模块 `taskId`、美团改价 `data` 任务串同一
 * 性质。若 RMS 对时效敏感，这层延迟要考虑进去。
 *
 * ============================================================================
 * changeRaw 的结构
 * ============================================================================
 *
 * ```
 * changeRaw
 * ├── status         0            ⚠️ 关房恒为 0（开房那条路走另一个端点）
 * ├── poiId          "1756785213" 门店，字符串
 * ├── roomId         413866969    物理房型，数字
 * ├── goodsIds       [952161333, 2429288289, 2429295192]
 * │                               ⚠️ **一个物理房型下的多个售卖商品**，见下
 * ├── date           "2026-08-17" ⚠️ **单个日期**，不是区间（开房那边是 startDate/endDate）
 * ├── roomName       "悦享大床房"  房型名，明文（不像携程是 HTML 实体编码）
 * ├── reason         ""           关房原因，用户可填，踩点样本里为空
 * ├── partnerId      4720332      商户号
 * ├── containerId    282464264    语义未知，原样保留
 * ├── pattern        1            语义未知
 * ├── limitType      1            语义未知
 * └── roomCategory   1            语义未知
 * ```
 *
 * ## ⚠️ `goodsIds` 是关房独有的，改价那边的 `goodsId` 与它同源
 *
 * 一个物理房型（`roomId`）下挂多个**售卖商品**（`goodsId`）——「不含早/含早」「预付/到付」
 * 这类组合各是一个 goods。关房是按物理房型关的，所以美团把该房型下**所有** goods 一并列出。
 *
 * 这与改价那条路的定位键是同一个东西：`amount-change-payload.ts` 里
 * `goodsList[].goodsBaseInfo.goodsId` 就是 RMS 追价台账的 `ota_sale_room_type_id`。
 * **RMS 反查门店/房型时用 `goodsIds` 比用 `roomId` 更直接** —— 台账里存的是前者。
 *
 * ## 日期：单值，不是区间
 *
 * 开房 `status/switch` 给的是 `startDate` + `endDate`（哪怕只关一天也是两个相同的值），
 * 关房只给一个 `date`。RMS 展开时不能套用同一套解析。
 *
 * ============================================================================
 * 裁剪：完全原样，一个字段不剔
 * ============================================================================
 *
 * 与美团房态房量的其余端点一致（见 `amount-change-adapter.ts` 的
 * `parseRoomStatusOrInventory`）：没有设备指纹/凭证/静态字典这类该剔的噪音，
 * 而 `containerId`/`pattern`/`limitType`/`roomCategory` 语义未确认 —— **看不懂正是不能剔
 * 的理由**，剔了永久丢失，RMS 日后踩清就能直接用。
 *
 * ============================================================================
 * ⚠️ 紧跟着的 deductRoomCount 不上报
 * ============================================================================
 *
 * 关房成功后美团前端会立刻再打一个
 * `POST /api/gw/v1/order/others/deductRoomCount`（`{poiId, roomId, roomType, closeTime}`），
 * 扣减该房型的可售房量。
 *
 * **它是关房的连带后果，不是用户的独立操作** —— 拦了会让一次关房产生两条上报、两个
 * `operationId`，RMS 会以为用户改了两次（与 `inventory/check` 双发同一类问题）。
 * 房量的变化 RMS 可以从「关房」这个事实自行推导。
 */
import type { JsonObject } from '../../../shared/types/json';

/**
 * 美团关房的 `changeRaw`。
 *
 * 用 `JsonObject` 的宽松形状而非逐字段严格类型，与其余渠道同一理由：desktop **忠实透传、
 * 不解读语义**，逐字段建模等于在这里复刻美团的房态语义，而美团随时可能加字段（加了就会被
 * 静默丢弃）。类型的作用是**说明结构**，校验只做到「能不能定位」为止。
 */
export type MeituanRoomCloseRaw = JsonObject &
  Readonly<{
    /** 关房恒为 `0`。开房不走这个端点，见文件头。 */
    status?: number;
    /** 门店 ID，字符串。 */
    poiId?: string;
    /** 物理房型 ID，数字。 */
    roomId?: number;
    /** 该物理房型下的全部售卖商品 —— RMS 反查用这个，见文件头。 */
    goodsIds?: readonly unknown[];
    /** ⚠️ 单个日期，不是区间。 */
    date?: string;
    /** 关房原因，用户可填。 */
    reason?: string;
  }>;
